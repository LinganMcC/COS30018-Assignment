"""How much do results move between training runs? Mean and spread over seeds.

For each configuration behind a Sprint 3 decision: the original run (seed 42)
and the reruns from seed_runs.py (seeds 43, 44). Reports validation, MNIST
test and shifted-test accuracy from the run summaries, and accuracy on the 149
real digit photos scored here from each run's checkpoint.

    python seed_variation.py   ->  ../experiments/eval/seed_variation.md (+ .json)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TUNING = HERE.parent / "checkpoints" / "tuning"
SUMMARIES = HERE.parent / "experiments" / "tuning"
OUT = HERE.parent / "experiments" / "eval" / "seed_variation.md"

CONFIGS = {   # name -> (label, original run with seed 42)
    "A1": ("VGG-deep, no augmentation (A1)", "s3_A1_aug_none"),
    "A2": ("VGG-deep, light augmentation (A2)", "s3_A2_aug_light"),
    "B3": ("VGG-deep, dropout 0.3 (B3)", "s3_B3_drop_0.3"),
    "B5": ("VGG-deep, batch 64 (B5 = cnn_best)", "s3_B5_bs_64"),
    "lenet": ("LeNet-5 (best settings)", "pm_lenet_best"),
    "resnet": ("ResNet (best settings)", "pm_resnet_best"),
}


def real_digits():
    sys.path.insert(0, str(REPO / "src"))
    from preprocessing import preprocess
    from test_set import load_digits
    items = load_digits()
    x = np.stack([preprocess(img, add_channel=True) for _, img, _ in items])
    y = np.array([int(lbl) for _, _, lbl in items])
    return x, y


def main():
    import tensorflow as tf
    x_real, y_real = real_digits()
    data, lines = {}, []
    for key, (label, original) in CONFIGS.items():
        runs = [original] + [f"seed_{key}_s{s}" for s in (43, 44)]
        runs = [r for r in runs if (SUMMARIES / f"{r}_summary.json").exists() and (TUNING / f"{r}.keras").exists()]
        rec = {"runs": runs, "val": [], "test": [], "shifted": [], "real": [], "epochs": []}
        for r in runs:
            s = json.loads((SUMMARIES / f"{r}_summary.json").read_text())
            model = tf.keras.models.load_model(TUNING / f"{r}.keras")
            rec["val"].append(s["val_accuracy"]); rec["test"].append(s["test_accuracy"])
            rec["shifted"].append(s["robust_test_accuracy"]); rec["epochs"].append(s["epochs_run"])
            rec["real"].append(float((model.predict(x_real, verbose=0).argmax(1) == y_real).mean()))
        data[key] = rec

        def ms(v):
            return f"{100 * np.mean(v):.2f} ± {100 * np.std(v, ddof=1):.2f}" if len(v) > 1 else f"{100 * v[0]:.2f}"
        lines.append(f"| {label} | {len(runs)} | {ms(rec['val'])} | {ms(rec['test'])} | {ms(rec['shifted'])} | {ms(rec['real'])} |")
        print(label, len(runs), flush=True)
    md = ["# Run-to-run variation over seeds", "",
          "Generated by `python seed_variation.py`. Mean ± standard deviation (percentage points) over "
          "the original run (seed 42) and reruns with seeds 43 and 44 (`seed_runs.py`); nothing else changed. "
          "Real digits = the 149 photographed single digits.", "",
          "| Configuration | Runs | Validation | MNIST test | Shifted test | Real digits |",
          "|---|---|---|---|---|---|"] + lines + [""]
    OUT.write_text("\n".join(md))
    OUT.with_suffix(".json").write_text(json.dumps(data, indent=1))
    print("->", OUT)


if __name__ == "__main__":
    main()
