"""Re-check the Sprint 3 choices without touching any test set.

In Sprint 3 two decisions used the shifted TEST set: keeping 'light' augmentation
(stage A) and breaking the B3/B5 validation tie. This script repeats both
decisions on a shifted copy of the VALIDATION set instead, so the test sets go
back to being reported only.

The rule was fixed before any model was scored (written here first):

    shifted validation  the 6,000 validation images, each perturbed once with the
                        same settings as the shifted test set (rotation 15 deg,
                        shift 12 %, zoom 12 %) but a different seed (1, test uses 0)
    stage A             augmentation level with the highest mean of clean and
                        shifted validation accuracy (augmentation exists to make
                        the model robust without hurting clean accuracy)
    stage B             highest clean validation accuracy; ties (same value to
                        4 decimals) broken by shifted validation, then training time

Uses the tuning checkpoints in models/checkpoints/tuning/ (kept locally, not in Git).

    python reselect_shifted_val.py        ->  ../experiments/eval/reselection_shifted_val.md
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from augmentation import make_shifted_test_set
from mnist_loader import load_mnist

HERE = Path(__file__).resolve().parent
TUNING = HERE.parent / "checkpoints" / "tuning"
SUMMARIES = HERE.parent / "experiments" / "tuning"
OUT = HERE.parent / "experiments" / "eval" / "reselection_shifted_val.md"
STAGE_A = ["s3_A1_aug_none", "s3_A2_aug_light", "s3_A3_aug_medium", "s3_A4_aug_strong"]
STAGE_B = ["s3_B1_lr_3e-4", "s3_B2_lr_3e-3", "s3_B3_drop_0.3", "s3_B4_drop_0.7",
           "s3_B5_bs_64", "s3_B6_bs_256"]
SHIFTED_VAL_SEED = 1


def accuracy(model, x, y) -> float:
    return float((model.predict(x, batch_size=512, verbose=0).argmax(1) == y).mean())


def main():
    import tensorflow as tf
    (_, _), (x_val, y_val), _ = load_mnist()
    x_val_shifted = make_shifted_test_set(x_val, seed=SHIFTED_VAL_SEED)
    rows = {}
    for run in STAGE_A + STAGE_B:
        model = tf.keras.models.load_model(TUNING / f"{run}.keras")
        s = json.loads((SUMMARIES / f"{run}_summary.json").read_text())
        rows[run] = {"val": accuracy(model, x_val, y_val),
                     "val_shifted": accuracy(model, x_val_shifted, y_val),
                     "logged_val": s["val_accuracy"], "time": s["training_time_s"],
                     "test": s["test_accuracy"], "test_shifted": s["robust_test_accuracy"]}
        print(run, {k: round(v, 4) for k, v in rows[run].items()}, flush=True)

    a_pick = max(STAGE_A, key=lambda r: (rows[r]["val"] + rows[r]["val_shifted"]) / 2)
    b_pick = max(STAGE_B, key=lambda r: (round(rows[r]["val"], 4), rows[r]["val_shifted"], -rows[r]["time"]))

    def table(runs, extra):
        lines = ["| Run | Validation | Shifted validation | " + extra[0] + " | Test (reported only) | Shifted test (reported only) |",
                 "|---|---|---|---|---|---|"]
        for r in runs:
            v = rows[r]
            lines.append(f"| {r}{' **(chosen)**' if r in (a_pick, b_pick) else ''} | {100*v['val']:.2f} % | "
                         f"{100*v['val_shifted']:.2f} % | {extra[1](v)} | {100*v['test']:.2f} % | {100*v['test_shifted']:.2f} % |")
        return lines

    md = ["# Sprint 3 choices re-checked on a shifted validation set", "",
          "Generated by `python reselect_shifted_val.py`. Rule fixed before scoring (see the script).", "",
          "## Stage A – augmentation (chosen by the mean of clean and shifted validation)", ""]
    md += table(STAGE_A, ("Mean", lambda v: f"{50*(v['val']+v['val_shifted']):.2f} %"))
    md += ["", "## Stage B – one hyperparameter at a time (clean validation; ties by shifted validation)", ""]
    md += table(STAGE_B, ("Training time", lambda v: f"{v['time']:.0f} s"))
    a_scores = sorted(((rows[r]["val"] + rows[r]["val_shifted"]) / 2, r) for r in STAGE_A)
    margin_images = (a_scores[-1][0] - a_scores[-2][0]) * len(y_val)
    md += ["", f"Chosen: stage A **{a_pick}**, stage B **{b_pick}**. "
           f"Sprint 3 chose s3_A2_aug_light and s3_B5_bs_64.", "",
           f"Stage A margin over the runner-up ({a_scores[-2][1]}): {margin_images:.1f} validation "
           f"images out of {len(y_val):,} on the mean of the two measures. Re-running one "
           "configuration with another seed moves validation accuracy by about 0.1 point "
           "(6 images), so a margin below 6 images is a tie, not a preference.", ""]
    OUT.write_text("\n".join(md))
    print("->", OUT, "| A:", a_pick, "| B:", b_pick)


if __name__ == "__main__":
    main()
